def main() -> None:
    Base.metadata.drop_all(engine)
    init_db()
    with SessionLocal() as db:
        auth.register(
            db,
            email="customer@example.com",
            password=PASSWORD,
            full_name="Demo Customer",
            role="customer",
            company_name=None,
        )
        for (email, name), cars in COMPANIES.items():
            company = auth.register(
                db,
                email=email,
                password=PASSWORD,
                full_name=f"{name} Admin",
                role="company",
                company_name=name,
            )
            for (
                brand,
                model,
                year,
                category,
                seats,
                transmission,
                fuel,
                price,
                city,
                dlat,
                dlng,
            ) in cars:
                lat, lng = CITIES[city]
                db.add(
                    Car(
                        owner_id=company.id,
                        brand=brand,
                        model=model,
                        year=year,
                        category=category,
                        seats=seats,
                        transmission=transmission,
                        fuel=fuel,
                        daily_price=Decimal(price),
                        city=city,
                        lat=lat + dlat,
                        lng=lng + dlng,
                    )
                )
        db.commit()
    print("Seed complete.")


if __name__ == "__main__":
    main()
